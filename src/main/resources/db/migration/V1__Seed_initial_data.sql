--Создать все схемы
CREATE SCHEMA IF NOT EXISTS users;
CREATE SCHEMA IF NOT EXISTS publications;
CREATE SCHEMA IF NOT EXISTS storage;
CREATE SCHEMA IF NOT EXISTS server_settings;

--что-то с пользователями
CREATE TABLE IF NOT EXISTS users.users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    login           VARCHAR(255) NOT NULL,
    password        VARCHAR(255),
    avatar_uri      VARCHAR(255),
    name            VARCHAR(255),
    bio             VARCHAR(255),
    email           VARCHAR(255) UNIQUE,
    created_at      TIMESTAMP WITHOUT TIME ZONE,
    role            BIGINT,
    numb_of_followers   BIGINT,
    numb_of_followings  BIGINT,
    CONSTRAINT pk_users PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS users.following(
    id              UUID not null,
    follower_id     BIGINT,
    follow_id       BIGINT,
    created_at      TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_followers PRIMARY KEY (id)
);

ALTER TABLE users.following
    ADD CONSTRAINT uq_follow UNIQUE (follower_id, follow_id);

ALTER TABLE users.following
    ADD CONSTRAINT FK_FOLLOWERS_ON_USERS_FOLLOWER FOREIGN KEY (follower_id) REFERENCES users.users (id) ON DELETE CASCADE;
ALTER TABLE users.following
    ADD CONSTRAINT FK_FOLLOWERS_ON_USERS_FOLLOW FOREIGN KEY (follow_id) REFERENCES users.users (id) ON DELETE CASCADE;

--публикации и связанное с ними все
CREATE TABLE IF NOT EXISTS publications.publications (
        id              UUID DEFAULT gen_random_uuid() NOT NULL,
        author_id        BIGINT,
        publication_type BIGINT, --вот это ENUM в коде думаю
        category_id      BIGINT,
        title           VARCHAR(300),
        description     VARCHAR(2000),
        latitude        DECIMAL(10, 7),
        longitude       DECIMAL(10, 7),
        region          VARCHAR(255),
        city            VARCHAR(255),
        likes_count     BIGINT,
        comments_count  BIGINT,
        parent_publication_id  UUID,
        created_at      TIMESTAMP WITHOUT TIME ZONE,
        end_date        TIMESTAMP WITHOUT TIME ZONE,
        CONSTRAINT pk_publications PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS publications.likes(
        id               UUID DEFAULT gen_random_uuid() NOT NULL,
        author_id        BIGINT,
        publication_id   UUID,
        created_at      TIMESTAMP WITHOUT TIME ZONE,
        CONSTRAINT pk_likes PRIMARY KEY (id)
);

ALTER TABLE publications.likes
    ADD CONSTRAINT FK_LIKES_ON_USERS FOREIGN KEY (author_id) REFERENCES users.users (id) ON DELETE CASCADE ;
ALTER TABLE publications.likes
    ADD CONSTRAINT FK_LIKES_ON_publications FOREIGN KEY (publication_id) REFERENCES publications.publications (id) ON DELETE CASCADE;
ALTER TABLE publications.likes
    ADD CONSTRAINT uq_like UNIQUE (author_id, publication_id);

CREATE TABLE IF NOT EXISTS publications.comments(
        id               UUID DEFAULT gen_random_uuid() NOT NULL,
        author_id        BIGINT,
        publication_id   UUID,
        parent_id        UUID,
        content          VARCHAR(2000),
        mentioned_user_id BIGINT,
        created_at      TIMESTAMP WITHOUT TIME ZONE,
        CONSTRAINT pk_comments PRIMARY KEY (id)
);

ALTER TABLE publications.comments
    ADD CONSTRAINT FK_COMMENTS_ON_USERS FOREIGN KEY (author_id) REFERENCES users.users (id) ON DELETE CASCADE;
ALTER TABLE publications.comments
    ADD CONSTRAINT FK_COMMENTS_ON_publications FOREIGN KEY (publication_id) REFERENCES publications.publications (id) ON DELETE CASCADE;
ALTER TABLE publications.comments
    ADD CONSTRAINT FK_COMMENTS_ON_COMMENTS FOREIGN KEY (parent_id) REFERENCES publications.comments(id) ON DELETE CASCADE;
ALTER TABLE publications.comments
    ADD CONSTRAINT FK_COMMENTS_ON_MENTIONED_USER
        FOREIGN KEY (mentioned_user_id) REFERENCES users.users (id) ON DELETE CASCADE;

CREATE TABLE IF NOT EXISTS publications.place_categories(
        id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
        title           VARCHAR(255),
        CONSTRAINT pk_categories PRIMARY KEY (id)
);

ALTER TABLE publications.publications
    ADD CONSTRAINT FK_PUBLICATIONS_ON_CATEGORIES FOREIGN KEY (category_id) REFERENCES publications.place_categories (id);
ALTER TABLE publications.publications
    ADD CONSTRAINT FK_PUBLICATIONS_ON_USERS FOREIGN KEY (author_id) REFERENCES users.users (id) ON DELETE CASCADE;
ALTER TABLE publications.publications
    ADD CONSTRAINT FK_PUBLICATIONS_ON_PUBLICATIONS FOREIGN KEY (parent_publication_id) REFERENCES publications.publications (id);

CREATE TABLE IF NOT EXISTS publications.tags(
        id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
        title           VARCHAR(255),
        CONSTRAINT pk_tags PRIMARY KEY (id)
);

--хранилище кароче
CREATE TABLE IF NOT EXISTS storage.attachment(
        id              UUID DEFAULT gen_random_uuid() NOT NULL,
        publication_id  UUID,
        type            BIGINT,
        file_uri        VARCHAR(500),
        photo_order     BIGINT,
        bucket_id       UUID,
        created_at      TIMESTAMP WITHOUT TIME ZONE,
        CONSTRAINT pk_attachment PRIMARY KEY (id)
);

ALTER TABLE storage.attachment
    ALTER COLUMN publication_id DROP NOT NULL;

CREATE TABLE storage.attachment_type
(
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title VARCHAR(255),
    CONSTRAINT pk_attachment_type PRIMARY KEY (id)
);

ALTER TABLE storage.attachment
    ADD CONSTRAINT FK_ATTACHMENT_ON_PUBLICATION FOREIGN KEY (publication_id) REFERENCES publications.publications (id) ON DELETE CASCADE;
ALTER TABLE storage.attachment
    ADD CONSTRAINT FK_ATTACHMENT_ON_ATTACHMENT_TYPE FOREIGN KEY (type) REFERENCES storage.attachment_type (id);

CREATE TABLE IF NOT EXISTS storage.bucket(
    id              UUID DEFAULT gen_random_uuid() NOT NULL,
    bucket_name     VARCHAR(255) UNIQUE,
    owner_id        BIGINT,
    CONSTRAINT pk_bucket PRIMARY KEY (id)
);

ALTER TABLE storage.attachment
    ADD CONSTRAINT fk_attachment_bucket FOREIGN KEY (bucket_id) REFERENCES storage.bucket (id);
ALTER TABLE storage.bucket
    ADD CONSTRAINT fk_bucket_owner FOREIGN KEY (owner_id) REFERENCES users.users (id);

CREATE TABLE IF NOT EXISTS publications.publication_tags (
    publication_id UUID NOT NULL,
    tag_id         BIGINT NOT NULL,
    CONSTRAINT pk_publication_tags PRIMARY KEY (publication_id, tag_id),
    CONSTRAINT fk_pt_publication FOREIGN KEY (publication_id)
    REFERENCES publications.publications (id) ON DELETE CASCADE,
    CONSTRAINT fk_pt_tag FOREIGN KEY (tag_id)
    REFERENCES publications.tags (id) ON DELETE CASCADE
    );


--для токенов
CREATE TABLE IF NOT EXISTS server_settings.jwt_keys(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    key_type        VARCHAR(50),
    key_value       BYTEA,
    created_at      TIMESTAMP WITHOUT TIME ZONE,
    updated_at      TIMESTAMP WITHOUT TIME ZONE,
    is_active       BOOLEAN DEFAULT TRUE,
    CONSTRAINT pk_iwt_keys  PRIMARY KEY (id)
);


