    id              UUID DEFAULT gen_random_uuid() NOT NULL,
    discussion_id  UUID,
    type            BIGINT,
    file_uri        VARCHAR(500),
    photo_order     BIGINT,
    bucket_id       UUID,   --так же как и у файлов публикации - в бакет пользователя-владельца ыыы
    created_at      TIMESTAMP WITHOUT TIME ZONE,
