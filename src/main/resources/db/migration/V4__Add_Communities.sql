    );

ALTER TABLE storage.discussion_attachment
    ADD CONSTRAINT FK_DISCUSSION_ON_DISCUSSION_ATTACHMENT FOREIGN KEY (discussion_id) REFERENCES publications.discussions(id) ON DELETE CASCADE;
ALTER TABLE storage.discussion_attachment
    ADD CONSTRAINT FK_ATTACHMENT_ON_DISCUSSION_ATTACHMENT FOREIGN KEY (type) REFERENCES storage.attachment_type (id);

CREATE TABLE IF NOT EXISTS publications.discussion_likes(
    id               UUID DEFAULT gen_random_uuid() NOT NULL,
    author_id        BIGINT,
    discussion_id   UUID,
    created_at      TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_likes PRIMARY KEY (id)
    );

ALTER TABLE publications.discussion_likes
    ADD CONSTRAINT FK_USERS_ON_DISCUSSION_LIKES FOREIGN KEY (author_id) REFERENCES users.users (id) ON DELETE CASCADE;

ALTER TABLE publications.discussion_likes
    ADD CONSTRAINT FK_DISCUSSION_ON_DISCUSSION_LIKES FOREIGN KEY (discussion_id) REFERENCES publications.discussions(id) ON DELETE CASCADE;



