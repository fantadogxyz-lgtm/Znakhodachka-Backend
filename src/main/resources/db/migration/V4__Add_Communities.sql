CREATE EXTENSION IF NOT EXISTS postgis;

--сообщества
CREATE TABLE IF NOT EXISTS publications.communities (
    id              UUID DEFAULT gen_random_uuid() NOT NULL,
    slug            VARCHAR(50) NOT NULL,
    title           VARCHAR(100) NOT NULL,
    description     TEXT,
    cover_uri       VARCHAR(255),
    creator_id      BIGINT NOT NULL,
    created_at      TIMESTAMP WITHOUT TIME ZONE,
    members_count   BIGINT DEFAULT 0,
    CONSTRAINT pk_communities PRIMARY KEY (id),
    CONSTRAINT uq_communities_slug UNIQUE (slug)
    );

ALTER TABLE publications.communities
    ADD CONSTRAINT FK_COMMUNITIES_ON_USERS FOREIGN KEY (creator_id)
        REFERENCES users.users (id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS idx_communities_creator ON publications.communities(creator_id);


CREATE TABLE IF NOT EXISTS publications.community_tags (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    community_id    UUID NOT NULL,
    title           VARCHAR(50) NOT NULL,
    created_at      TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_community_tags PRIMARY KEY (id),
    CONSTRAINT uq_community_tags UNIQUE (community_id, title)
    );

ALTER TABLE publications.community_tags
    ADD CONSTRAINT FK_COMMUNITY_TAGS_ON_COMMUNITIES FOREIGN KEY (community_id)
        REFERENCES publications.communities (id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS idx_community_tags_community ON publications.community_tags(community_id);

--участники сообществ
CREATE TABLE IF NOT EXISTS publications.community_participation (
    id              UUID DEFAULT gen_random_uuid() NOT NULL,
    community_id    UUID NOT NULL,
    user_id         BIGINT NOT NULL,
    joined_at       TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_community_participation PRIMARY KEY (id),
    CONSTRAINT uq_community_participation UNIQUE (community_id, user_id)
    );

ALTER TABLE publications.community_participation
    ADD CONSTRAINT FK_COMMUNITY_MEMBERS_ON_COMMUNITIES
        FOREIGN KEY (community_id) REFERENCES publications.communities (id) ON DELETE CASCADE;
ALTER TABLE publications.community_participation
    ADD CONSTRAINT FK_COMMUNITY_MEMBERS_ON_USERS
        FOREIGN KEY (user_id) REFERENCES users.users (id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS idx_community_participation_user
    ON publications.community_participation(user_id);
CREATE INDEX IF NOT EXISTS idx_community_participation_community
    ON publications.community_participation(community_id);

--привязка постов к сообществу
ALTER TABLE publications.publications
    ADD COLUMN IF NOT EXISTS community_id UUID;

ALTER TABLE publications.publications
    ADD CONSTRAINT FK_PUBLICATIONS_ON_COMMUNITIES FOREIGN KEY (community_id) REFERENCES publications.communities (id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS idx_publications_community ON publications.publications(community_id);

--спец-теги постов сообщества
CREATE TABLE IF NOT EXISTS publications.publication_community_tags (
    publication_id      UUID NOT NULL,
    community_tag_id    BIGINT NOT NULL,
    CONSTRAINT pk_publication_community_tags PRIMARY KEY (publication_id, community_tag_id)
    );

ALTER TABLE publications.publication_community_tags
    ADD CONSTRAINT FK_PCT_ON_PUBLICATIONS FOREIGN KEY (publication_id) REFERENCES publications.publications (id) ON DELETE CASCADE;
ALTER TABLE publications.publication_community_tags
    ADD CONSTRAINT FK_PCT_ON_COMMUNITY_TAGS FOREIGN KEY (community_tag_id) REFERENCES publications.community_tags (id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS idx_pub_comm_tags_tag ON publications.publication_community_tags(community_tag_id);

--обсуждения сообществ

CREATE TABLE IF NOT EXISTS publications.discussions(
    id              UUID DEFAULT gen_random_uuid() NOT NULL,
    text            VARCHAR(2000),
    type            BIGINT, --енам - главное обсуждение и комментарий
    topic_id        UUID,
    parent_id       UUID,
    author_id       BIGINT,
    mentioned_user_id BIGINT,
    community_id    UUID,
    created_at      TIMESTAMP WITHOUT TIME ZONE,
    count_of_likes  BIGINT DEFAULT 0,
    CONSTRAINT PK_discussions PRIMARY KEY (id)
);

ALTER TABLE publications.discussions
    ADD CONSTRAINT FK_DISCUSSIONS_ON_USERS FOREIGN KEY (author_id) REFERENCES users.users (id) ON DELETE CASCADE;

ALTER TABLE publications.discussions
    ADD CONSTRAINT FK_DISCUSSIONS_PARENT FOREIGN KEY (parent_id) REFERENCES publications.discussions(id) ON DELETE CASCADE;
ALTER TABLE publications.discussions
    ADD CONSTRAINT FK_DISCUSSIONS_TOPIC FOREIGN KEY (topic_id) REFERENCES publications.discussions(id) ON DELETE CASCADE;
ALTER TABLE publications.discussions
    ADD CONSTRAINT FK_DISCUSSIONS_COMMUNITY FOREIGN KEY (community_id) REFERENCES publications.communities(id) ON DELETE CASCADE;

CREATE TABLE IF NOT EXISTS publications.geolocations(
    id              UUID DEFAULT gen_random_uuid() NOT NULL,
    title           VARCHAR(100),
    latitude        DECIMAL(10, 7),
    longitude       DECIMAL(10, 7),
    CONSTRAINT PK_geolocations PRIMARY KEY (id)
);

ALTER TABLE publications.geolocations
    ADD COLUMN location geography(POINT, 4326);

UPDATE publications.geolocations
SET location = ST_MakePoint(longitude, latitude)::geography
WHERE latitude IS NOT NULL AND longitude IS NOT NULL;


